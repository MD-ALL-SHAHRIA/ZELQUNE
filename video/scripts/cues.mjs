// Prints the sound cue sheet (time, sound, triggering visual event) to SOUND_CUES.md, from the
// same cue list the video plays (src/audio/cues.ts).
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = await build({ entryPoints: [path.join(root, 'src/audio/cues.ts')], bundle: true, write: false, format: 'esm', platform: 'node', logLevel: 'error' });
const mod = await import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'));
const cues = mod.buildCues();
const ducks = mod.duckWindows();
const fmt = (f) => { const s = f / 30; return `${Math.floor(s / 60)}:${(s % 60).toFixed(2).padStart(5, '0')}`; };
const rows = cues.map((c) => `| ${fmt(c.frame)} | ${c.frame} | ${(c.frame / 15).toFixed(2)} | ${c.sfx} | ${c.volume.toFixed(2)} | ${c.rate.toFixed(2)} | ${c.event} |`);
const md = `# Sound cue sheet

Generated by \`node scripts/cues.mjs\` from src/audio/cues.ts (the list the video plays). 30 fps, 120 BPM,
1 beat = 15 frames. Volumes are before the global \`audio.sfxVolume\`.

Music: assets/music.mp3, fade in 0.5 s, fade out 1.5 s, ducked about -6 dB during:
${ducks.map(([a, b]) => `- ${fmt(a)} to ${fmt(b)}`).join('\n')}

${cues.length} cues.

| Time | Frame | Beat | Sound | Vol | Rate | Visual event |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(path.join(root, 'SOUND_CUES.md'), md);
console.log(`SOUND_CUES.md: ${cues.length} cues`);
